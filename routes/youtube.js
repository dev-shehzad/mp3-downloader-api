const express = require('express');
const router = express.Router();
const path = require('path');
const fs = require('fs');
const { v4: uuidv4 } = require('uuid');
const { create: createYtDlp } = require('yt-dlp-exec');
const { addID3Tags, TEMP_DIR, FFMPEG_PATH, getYtDlpPath } = require('../utils/helpers');

// Create yt-dlp runner with proper binary path
let ytDlpRunner;
function getYtRunner() {
  if (!ytDlpRunner) {
    const bin = getYtDlpPath();
    ytDlpRunner = bin === 'yt-dlp' ? require('yt-dlp-exec') : createYtDlp(bin);
  }
  return ytDlpRunner;
}

function ytDlp(url, options) {
  const runner = getYtRunner();
  return runner(url, {
    ...options,
    ...(FFMPEG_PATH && FFMPEG_PATH !== 'ffmpeg' ? { ffmpegLocation: path.dirname(FFMPEG_PATH) } : {})
  });
}

// GET /api/youtube/info?url=...
router.get('/info', async (req, res) => {
  let { url } = req.query;
  if (!url) return res.status(400).json({ error: 'URL is required' });

  // Clean radio/mix URLs (list=RD...) to pure video URL because RD mixes are autogenerated YouTube radios
  const isMix = url.includes('list=RD');
  const isPlaylist = (url.includes('/playlist') || url.includes('list=PL') || url.includes('list=UU') || url.includes('list=FL') || url.includes('list=OLAK')) && !isMix;
  let cleanUrl = url;
  if (isMix && cleanUrl.includes('watch?v=')) {
    cleanUrl = cleanUrl.replace(/[&?]list=RD[^&]*/, '').replace(/[&?]start_radio=[^&]*/, '');
  }

  try {
    const info = await ytDlp(cleanUrl, {
      dumpSingleJson: true,
      noWarnings: true,
      noCheckCertificates: true,
      preferFreeFormats: true,
      extractorArgs: 'youtube:player_client=android,web',
      noPlaylist: !isPlaylist,
    });

    if (info.entries) {
      return res.json({
        type: 'playlist',
        title: info.title,
        uploader: info.uploader || '',
        count: info.entries.length,
        entries: info.entries.map(e => ({
          id: e.id,
          title: e.title,
          duration: e.duration,
          url: `https://www.youtube.com/watch?v=${e.id}`,
          thumbnail: e.thumbnail
        }))
      });
    } else {
      return res.json({
        type: 'video',
        id: info.id,
        title: info.title,
        uploader: info.uploader || info.channel || '',
        duration: info.duration,
        thumbnail: info.thumbnail,
        url: url
      });
    }
  } catch (err) {
    console.error('YouTube info error:', err.message);
    res.status(500).json({ error: 'Failed to fetch video info.' });
  }
});

// GET & POST /api/youtube/download
router.all('/download', async (req, res) => {
  req.setTimeout(0); // Disable timeout for large downloads
  const url = req.query.url || req.body?.url;
  const title = req.query.title || req.body?.title || 'audio';
  const uploader = req.query.uploader || req.body?.uploader || '';
  const thumbnail = req.query.thumbnail || req.body?.thumbnail || '';

  if (!url) return res.status(400).json({ error: 'URL is required' });

  const fileId = uuidv4();
  const safeTitle = title.replace(/[^\w\s-]/g, '').trim().substring(0, 100) || 'audio';
  const outputPath = path.join(TEMP_DIR, `${fileId}.mp3`);

  let cleanUrl = url;
  if (cleanUrl.includes('list=RD') && cleanUrl.includes('watch?v=')) {
    cleanUrl = cleanUrl.replace(/[&?]list=RD[^&]*/, '').replace(/[&?]start_radio=[^&]*/, '');
  }

  try {
    await ytDlp(cleanUrl, {
      output: outputPath,
      extractAudio: true,
      audioFormat: 'mp3',
      audioQuality: '0',
      postprocessorArgs: 'ffmpeg:-b:a 320k -ar 44100',
      noWarnings: true,
      noCheckCertificates: true,
      extractorArgs: 'youtube:player_client=android,web',
      noPlaylist: true,
    });

    if (fs.existsSync(outputPath)) {
      await addID3Tags(outputPath, { title: safeTitle, artist: uploader, thumbnail });
    }

    const filename = encodeURIComponent(`${safeTitle}.mp3`);
    res.setHeader('Content-Disposition', `attachment; filename*=UTF-8''${filename}`);
    res.setHeader('Content-Type', 'audio/mpeg');

    const stream = fs.createReadStream(outputPath);
    stream.pipe(res);
    stream.on('end', () => { try { fs.unlinkSync(outputPath); } catch (e) {} });
    stream.on('error', () => { try { fs.unlinkSync(outputPath); } catch (e) {} });

  } catch (err) {
    console.error('YouTube download error:', err.message);
    if (fs.existsSync(outputPath)) { try { fs.unlinkSync(outputPath); } catch (e) {} }
    res.status(500).json({ error: `Download failed: ${err.message}` });
  }
});

// GET /api/youtube/search-page?url=...&keyword=...
router.get('/search-page', async (req, res) => {
  const { url, keyword = '' } = req.query;
  if (!url) return res.status(400).json({ error: 'URL is required' });

  try {
    const info = await ytDlp(url, {
      dumpSingleJson: true,
      flatPlaylist: true,
      noWarnings: true,
      noCheckCertificates: true,
      extractorArgs: 'youtube:player_client=android,web',
      playlistEnd: 200,
    });

    let entries = info.entries || (info.id ? [info] : []);
    if (keyword.trim()) {
      const kw = keyword.toLowerCase();
      entries = entries.filter(e => (e.title || '').toLowerCase().includes(kw));
    }

    res.json({
      type: 'list',
      total: entries.length,
      keyword,
      entries: entries.map(e => ({
        id: e.id,
        title: e.title || 'Unknown',
        duration: e.duration,
        url: e.url || `https://www.youtube.com/watch?v=${e.id}`,
        thumbnail: e.thumbnail
      }))
    });
  } catch (err) {
    console.error('Search page error:', err.message);
    res.status(500).json({ error: 'Failed to fetch page videos.' });
  }
});

module.exports = router;
